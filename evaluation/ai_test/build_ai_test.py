def write_case(out, c, kb):
    src_info = []
    for sid in c["sources"]:
        r = kb.get(sid)
        if r is None:
            raise SystemExit(f"BUG: gold_source_id {sid} not found in KB ({c['test_id']})")
        src_info.append({"source_id": sid, "title": r["title"], "source_type": r["source_type"]})
    out["test_id"] = c["test_id"]
    out["group_id"] = c["group_id"]
    out["split"] = c["split"]
    out["role"] = c["role"]
    out["answerable"] = c["answerable"]
    out["messages"] = c["messages"]
    out["actions"] = []
    out["expected_outcome"] = c["expected_outcome"]
    out["gold_source_ids"] = c["sources"]
    out["required_conditions"] = c["conditions"]
    out["forbidden_claims"] = c["forbidden"]
    out["gold_line"] = c["gold_line"]
    out["allowed_lines"] = c["allowed_lines"]
    out["recipient"] = c["recipient"]
    out["evidence_refs"] = src_info


def main():
    kb = load_kb()
    all_cases = cases()
    dev = [c for c in all_cases if c["split"] == "dev"]
    fin = [c for c in all_cases if c["split"] == "final"]
    if len(dev) != 20:
        raise SystemExit(f"dev expected 20 got {len(dev)}")
    if len(fin) != 40:
        raise SystemExit(f"final expected 40 got {len(fin)}")
    # uniqueness
    ids = [c["test_id"] for c in all_cases]
    assert len(set(ids)) == len(ids), "duplicate test_id"
    # groups must not cross split
    gdev = {c["group_id"] for c in dev}
    gfin = {c["group_id"] for c in fin}
    assert not (gdev & gfin), "group crossed dev<->final"

    os.makedirs(DEV_PATH, exist_ok=True)
    os.makedirs(FINAL_PATH, exist_ok=True)

    def dump(cases_list, path):
        rows = []
        for c in sorted(cases_list, key=lambda x: x["test_id"]):
            row = {}
            write_case(row, c, kb)
            rows.append(row)
        with open(path, "w", encoding="utf-8") as f:
            for row in rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        return rows

    dev_rows = dump(dev, os.path.join(DEV_PATH, "ai_test_dev.jsonl"))
    fin_rows = dump(fin, os.path.join(FINAL_PATH, "ai_test_final.jsonl"))

    def sha(path):
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
        return h.hexdigest()

    dev_manifest = {
        "schema": "tenderhack.ai_test_manifest/dev-v1",
        "set": "dev",
        "count": len(dev_rows),
        "groups": sorted(gdev),
        "file": "ai_test_dev.jsonl",
        "sha256": sha(os.path.join(DEV_PATH, "ai_test_dev.jsonl")),
        "generated_at": None,
        "cases": [
            {"test_id": r["test_id"], "group_id": r["group_id"], "answerable": r["answerable"],
             "gold_source_ids": r["gold_source_ids"], "hashes": {"sha256_case": hashlib.sha256(
                json.dumps(r, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()}}
            for r in dev_rows
        ],
    }
    with open(DEV_MANIFEST, "w", encoding="utf-8") as f:
        json.dump(dev_manifest, f, ensure_ascii=False, indent=2)

    final_manifest = {
        "schema": "tenderhack.ai_test_manifest/final-v1",
        "set": "final",
        "count": len(fin_rows),
        "groups": sorted(gfin),
        "storage": "evaluation/final_private/ai_test_final.jsonl (gitignored, sealed)",
        "sha256": sha(os.path.join(FINAL_PATH, "ai_test_final.jsonl")),
        "note": "Content sealed outside checkout; only hashes in repository.",
        "cases": [
            {"test_id": r["test_id"], "group_id": r["group_id"], "answerable": r["answerable"],
             "gold_source_ids": r["gold_source_ids"], "hashes": {"sha256_case": hashlib.sha256(
                json.dumps(r, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()}}
            for r in fin_rows
        ],
    }
    with open(FINAL_MANIFEST, "w", encoding="utf-8") as f:
        json.dump(final_manifest, f, ensure_ascii=False, indent=2)

    print("OK dev=%d final=%d" % (len(dev_rows), len(fin_rows)))
    print("dev sha", dev_manifest["sha256"])
